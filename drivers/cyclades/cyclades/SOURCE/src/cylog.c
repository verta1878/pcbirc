/* ---- Hardware failures (critical) ---- */

VOID CyLogNoChipsFound(
    PDEVICE_OBJECT  DevObj,
    PHYSICAL_ADDRESS MemAddress)
{
    ULONG data[2];
    data[0] = MemAddress.LowPart;
    data[1] = MemAddress.HighPart;

    CyLogEvent(DevObj, CYLOG_NO_CHIPS_FOUND, 0,
               data, 2, STATUS_DEVICE_DOES_NOT_EXIST);

    CyError("EVENT: No CD1400 chips found at 0x%08X%08X\n",
            MemAddress.HighPart, MemAddress.LowPart);
}

VOID CyLogMemoryMapFailed(
    PDEVICE_OBJECT  DevObj,
    PHYSICAL_ADDRESS MemAddress,
    ULONG           Length)
{
    ULONG data[3];
    data[0] = MemAddress.LowPart;
    data[1] = MemAddress.HighPart;
    data[2] = Length;

    CyLogEvent(DevObj, CYLOG_MEMORY_MAP_FAILED, 0,
               data, 3, STATUS_INSUFFICIENT_RESOURCES);

    CyError("EVENT: MmMapIoSpace failed at 0x%08X%08X (%lu bytes)\n",
            MemAddress.HighPart, MemAddress.LowPart, Length);
}

VOID CyLogInterruptConnectFailed(
    PDEVICE_OBJECT  DevObj,
    NTSTATUS        NtStatus)
{
    ULONG data[1];
    data[0] = (ULONG)NtStatus;

    CyLogEvent(DevObj, CYLOG_INTERRUPT_CONNECT_FAILED, 0,
               data, 1, NtStatus);

    CyError("EVENT: IoConnectInterrupt failed: 0x%08X\n", NtStatus);
}


