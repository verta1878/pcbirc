#define CYPORT_LEVEL_INFO       TRACE_LEVEL_INFORMATION
#define CYPORT_LEVEL_VERBOSE    TRACE_LEVEL_VERBOSE

/* Trace flag constants — map to bit positions in the control GUID.
 * These are used as the second argument to TraceEvents. In non-WPP
 * builds they're ignored (the DbgPrint fallback only uses level). */
#define CYPORT_INIT     0x001
#define CYPORT_PNP      0x002
#define CYPORT_POWER    0x004
#define CYPORT_IOCTL    0x008
#define CYPORT_READ     0x010
#define CYPORT_WRITE    0x020
#define CYPORT_ISR      0x040
#define CYPORT_HW       0x080
#define CYPORT_FLOW     0x100
#define CYPORT_MODEM    0x200

/* Map TraceEvents to our DbgPrint macros */
#define TraceEvents(level, flag, fmt, ...)                             \
    do {                                                               \
        if ((level) <= 2)      CyError(fmt "\n", ##__VA_ARGS__);        \
        else if ((level) <= 3) CyWarn(fmt "\n", ##__VA_ARGS__);         \
        else if ((level) <= 4) CyInfo(fmt "\n", ##__VA_ARGS__);         \
        else                   CyVerbose(fmt "\n", ##__VA_ARGS__);      \
    } while (0)

#endif /* WPP_ENABLED */


/* ====================================================================
 * FUNCTION ENTRY/EXIT TRACING
 * ====================================================================
 * These macros generate entry/exit traces with consistent formatting.
 * The function name is automatically captured via __FUNCTION__.
 *
 * Usage:
 *   NTSTATUS CyCreate(PDEVICE_OBJECT DevObj, PIRP Irp)
 *   {
 *       CY_FUNC_ENTER();
 *       ...
 *       CY_FUNC_EXIT(status);
 *   }
 * ==================================================================== */

#define CY_FUNC_ENTER()                                                \
    TraceEvents(CYPORT_LEVEL_VERBOSE, CYPORT_INIT,                     \
                "--> %s", __FUNCTION__)

#define CY_FUNC_EXIT(status)                                           \
    TraceEvents(CYPORT_LEVEL_VERBOSE, CYPORT_INIT,                     \
                "<-- %s: 0x%08X", __FUNCTION__, (ULONG)(status))

#define CY_FUNC_EXIT_VOID()                                           \
    TraceEvents(CYPORT_LEVEL_VERBOSE, CYPORT_INIT,                     \
                "<-- %s", __FUNCTION__)


/* ====================================================================
 * IRP TRACING
 * ====================================================================
 * Trace every IRP received with major/minor function codes.
 * ==================================================================== */

#define CY_TRACE_IRP(irp, major, minor)                                \
    TraceEvents(CYPORT_LEVEL_INFO, CYPORT_IOCTL,                      \
                "IRP %p: MJ=%d MN=%d",                                 \
                (irp), (int)(major), (int)(minor))

#define CY_TRACE_IOCTL(irp, code)                                      \
    TraceEvents(CYPORT_LEVEL_INFO, CYPORT_IOCTL,                      \
                "IRP %p: IOCTL 0x%08X", (irp), (ULONG)(code))


#endif /* CYTRACE_H */
