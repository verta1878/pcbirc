#define CYPORT_LEVEL_WARNING    TRACE_LEVEL_WARNING     /* 3 */
#define CYPORT_LEVEL_INFO       TRACE_LEVEL_INFORMATION /* 4 */
#define CYPORT_LEVEL_VERBOSE    TRACE_LEVEL_VERBOSE     /* 5 */


